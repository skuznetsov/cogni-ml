def _generate_mps_inputs(torch: Any, posemb_layers: Any, device: Any) -> dict[str, Any]:
    def formula(shape: list[int], phase: float) -> Any:
        count = math.prod(shape)
        values = torch.arange(count, dtype=torch.float32, device=device)
        values.mul_(0.017).add_(phase).sin_().mul_(0.1)
        cosines = torch.arange(count, dtype=torch.float32, device=device)
        cosines.mul_(0.0031).add_(phase * 0.7).cos_().mul_(0.05)
        values.add_(cosines)
        del cosines
        return values.reshape(shape)

    inputs = {
        "img": formula(_INPUT_SHAPES["input.img"], _INPUT_PHASES["img"]),
        "txt": formula(_INPUT_SHAPES["input.txt"], _INPUT_PHASES["txt"]),
        "vec": formula(_INPUT_SHAPES["input.vec"], _INPUT_PHASES["vec"]),
        "vec_txt": formula(_INPUT_SHAPES["input.vec_txt"], _INPUT_PHASES["vec_txt"]),
    }
    rope_cos, rope_sin = posemb_layers.get_nd_rotary_pos_embed(
        [16, 56, 56],
        tuple(GEOMETRY["rope_grid"]),
        theta=GEOMETRY["rope_theta"],
        use_real=True,
        theta_rescale_factor=1,
        device=device,
    )
    inputs["rope_cos"] = rope_cos
    inputs["rope_sin"] = rope_sin
    expected = {
        "img": _INPUT_SHAPES["input.img"],
        "txt": _INPUT_SHAPES["input.txt"],
        "vec": _INPUT_SHAPES["input.vec"],
        "vec_txt": _INPUT_SHAPES["input.vec_txt"],
        "rope_cos": _INPUT_SHAPES["input.rope_cos"],
        "rope_sin": _INPUT_SHAPES["input.rope_sin"],
    }
    for name, shape in expected.items():
        value = inputs[name]
        if value.device.type != "mps" or value.dtype != torch.float32:
            raise ReferenceError(f"full-J input did not remain MPS F32: {name}")
        if list(value.shape) != shape:
            raise ReferenceError(f"full-J input shape mismatch: {name}")
    return inputs


def _build_chunked_sdpa_adapter(torch: Any, receipt: dict[str, Any]) -> Any:
    functional = torch.nn.functional

    def parallel_attention(
        q: tuple[Any, Any],
        k: tuple[Any, Any],
        v: tuple[Any, Any],
        img_q_len: int,
        img_kv_len: int,
        attn_mode: str | None = None,
        text_mask: Any = None,
        attn_param: dict[str, Any] | None = None,
    ) -> Any:
        if attn_mode != "magi_mp_causal":
            raise RuntimeError(f"Full-J adapter rejects attention mode {attn_mode!r}")
        if text_mask is not None or attn_param is None:
            raise RuntimeError("Full-J adapter requires one unmasked segment and explicit metadata")
        expected_boundaries = [0, VIDEO_TOKENS]
        if (attn_param.get("num_prompts") != 1
                or attn_param.get("chunk_size_tokens", 0) != 0
                or attn_param.get("prompt_video_boundaries_tokens") != expected_boundaries
                or attn_param.get("prompt_video_boundaries") != expected_boundaries
                or attn_param.get("txt_tokens_per_block") != TEXT_TOKENS):
            raise RuntimeError("Full-J adapter received unsupported segment metadata")
        if img_q_len != VIDEO_TOKENS or img_kv_len != VIDEO_TOKENS:
            raise RuntimeError("Full-J adapter requires exact video query/key lengths")

        query = torch.cat((q[0], q[1]), dim=1)
        key = torch.cat((k[0], k[1]), dim=1)
        value = torch.cat((v[0], v[1]), dim=1)
        expected_shape = (1, TOTAL_TOKENS, 16, 128)
        if any(tuple(tensor.shape) != expected_shape for tensor in (query, key, value)):
            raise RuntimeError("Full-J adapter received unexpected Q/K/V geometry")
        if any(tensor.device.type != "mps" for tensor in (query, key, value)):
            raise RuntimeError("Full-J adapter requires MPS Q/K/V")
        if any(tensor.dtype != torch.float32 for tensor in (query, key, value)):
            raise RuntimeError("Full-J adapter requires F32 Q/K/V")

        query_sequence = query.permute(0, 2, 1, 3)
        key_heads = key.permute(0, 2, 1, 3).contiguous()
        value_heads = value.permute(0, 2, 1, 3).contiguous()
        output_heads = torch.empty(
            (1, 16, TOTAL_TOKENS, 128), dtype=torch.float32, device=query.device
        )
        query_chunks = 0
        for start in range(0, TOTAL_TOKENS, QUERY_CHUNK):
            stop = min(start + QUERY_CHUNK, TOTAL_TOKENS)
            query_chunk = query_sequence[:, :, start:stop, :].contiguous()
            attended = functional.scaled_dot_product_attention(
                query_chunk,
                key_heads,
                value_heads,
                attn_mask=None,
                dropout_p=0.0,
                is_causal=False,
            )
            if attended.device.type != "mps" or attended.dtype != torch.float32:
                raise RuntimeError("Full-J MPS SDPA returned an unexpected device/dtype")
            output_heads[:, :, start:stop, :].copy_(attended)
            query_chunks += 1
            del query_chunk, attended

        output = output_heads.permute(0, 2, 1, 3).contiguous().flatten(2)
        receipt["calls"] += 1
        receipt["query_chunks"] += query_chunks
        receipt["max_query_chunk"] = max(receipt["max_query_chunk"], QUERY_CHUNK)
        return output

    return parallel_attention


def _make_rotary_capture(torch: Any, posemb_layers: Any, block_index: int,
                         captures: dict[str, Any], receipt: dict[str, int]) -> Any:
    def apply_rotary_capture(q: Any, k: Any, freqs_cis: Any,
                             head_first: bool = False) -> tuple[Any, Any]:
        q_rot, k_rot = posemb_layers.apply_rotary_emb(
            q, k, freqs_cis, head_first=head_first
        )
        if (q_rot.device.type != "mps" or k_rot.device.type != "mps"
                or q_rot.dtype != torch.float32 or k_rot.dtype != torch.float32):
            raise RuntimeError("Full-J RoPE Q/K left MPS F32")
        if list(q_rot.shape) != _CAPTURE_SHAPES["img.attn.q_rope"]:
            raise RuntimeError("Full-J RoPE Q shape mismatch")
        if list(k_rot.shape) != _CAPTURE_SHAPES["img.attn.k_rope"]:
            raise RuntimeError("Full-J RoPE K shape mismatch")
        captures[f"block{block_index}.img.attn.q_rope"] = q_rot.detach().clone()
        captures[f"block{block_index}.img.attn.k_rope"] = k_rot.detach().clone()
        receipt["calls"] += 1
        return q_rot, k_rot

    return apply_rotary_capture


def _run_block(torch: Any, upstream: Path, helpers: tuple[Any, ...],
               posemb_layers: Any, state: dict[str, Any], block_index: int,
               device: Any, adapter: Any, inputs: dict[str, Any],
               receipt: dict[str, Any]) -> tuple[Any, Any, Any, dict[str, Any]]:
    name = f"block{block_index}"
    captures: dict[str, Any] = {}
    rotary_receipt = {"calls": 0}
    block_type = block_reference._extract_pinned_block(
        upstream,
        torch,
        adapter,
        _make_rotary_capture(torch, posemb_layers, block_index, captures, rotary_receipt),
        helpers,
    )
    block = block_type(
        hidden_size=2048,
        heads_num=16,
        mlp_width_ratio=4.0,
        mlp_act_type="gelu_tanh",
        attn_mode="magi_mp_causal",
        qk_norm=True,
        qk_norm_type="rms",
        qkv_bias=True,
        dtype=torch.float32,
        device=torch.device("meta"),
    )
    block.load_state_dict(state, strict=True, assign=True)
    block.to(device=device, dtype=torch.float32).eval()
    del state
    block_reference._round_parameters_bf16_in_place(torch, block, device)

    attn_param = {
        "num_prompts": 1,
        "txt_tokens_per_block": TEXT_TOKENS,
        "prompt_video_boundaries_tokens": [0, VIDEO_TOKENS],
        "prompt_video_boundaries": [0, VIDEO_TOKENS],
        "chunk_size_tokens": 0,
        "seg_ar_attention_backend": "magi",
    }
    before_calls = receipt["calls"]
    try:
        with torch.inference_mode():
            img_output, txt_output = block(
                img=inputs["img"],
                txt=inputs["txt"],
                vec=inputs["vec"],
                vec_txt=inputs["vec_txt"],
                freqs_cis=(inputs["rope_cos"], inputs["rope_sin"]),
                text_mask=None,
                attn_param=attn_param,
                is_flash=False,
                txt_tokens_per_block=TEXT_TOKENS,
                prompt_video_boundaries=[0, VIDEO_TOKENS],
            )
    except Exception:
        raise
    if receipt["calls"] != before_calls + 1:
        raise ReferenceError(f"{name} did not make exactly one chunked SDPA adapter call")
    if rotary_receipt["calls"] != 1:
        raise ReferenceError(f"{name} did not make exactly one upstream RoPE call")
    for stream, output in (("img", img_output), ("txt", txt_output)):
        expected = _CAPTURE_SHAPES[f"{stream}.output"]
        if (output.device.type != "mps" or output.dtype != torch.float32
                or list(output.shape) != expected):
            raise ReferenceError(f"{name} {stream} output device/dtype/shape mismatch")
        captures[f"{name}.{stream}.output"] = output
    expected_names = {f"{name}.{capture}" for capture in _CAPTURE_SHAPES}
    if set(captures) != expected_names:
        raise ReferenceError(f"{name} capture inventory mismatch")
    return img_output, txt_output, block, captures


def _serialize_tensors(torch: Any, records: dict[str, Any]) -> tuple[bytes, dict[str, Any]]:
    if set(records) != set(EXPECTED_TENSOR_SHAPES):
        raise ReferenceError("terminal tensor inventory differs from the admitted 14 names")
    flat: list[Any] = []
    finite: list[Any] = []
    metadata: dict[str, Any] = {}
    offset = 0
    for name in sorted(EXPECTED_TENSOR_SHAPES):
        value = records[name]
        if value.device.type != "mps" or value.dtype != torch.float32:
            raise ReferenceError(f"terminal checkpoint is not MPS F32: {name}")
        if list(value.shape) != EXPECTED_TENSOR_SHAPES[name]:
            raise ReferenceError(f"terminal checkpoint shape changed: {name}")
        contiguous = value.detach().contiguous()
        size = int(contiguous.numel()) * 4
        metadata[name] = {
            "dtype": "F32",
            "shape": list(contiguous.shape),
            "offset_bytes": offset,
            "nbytes": size,
        }
        offset += size
        flat.append(contiguous.reshape(-1))
        finite.append(torch.isfinite(contiguous).all().to(dtype=torch.float32).reshape(1))
    if not flat or offset > SIDE_CAR_LIMIT:
        raise ReferenceError("terminal sidecar exceeds the 512 MiB bound")
    packed = torch.cat(flat + finite).to(device="cpu", dtype=torch.float32).contiguous()
    array = packed.numpy()
    value_count = offset // 4
    if not bool((array[value_count:] == 1.0).all()):
        raise ReferenceError("non-finite value in the one packed final MPS readback")
    raw = array[:value_count].astype("<f4", copy=False).tobytes()
    if len(raw) != offset:
        raise ReferenceError("terminal F32 sidecar extent mismatch")
    validate_tensor_layout(metadata, len(raw))
    return raw, metadata


def _publish_noreplace(path: Path, data: bytes) -> None:
    if not path.parent.is_dir():
        raise FileNotFoundError(f"output parent must already exist: {path.parent}")
    if os.path.lexists(path):
        raise FileExistsError(f"output already exists: {path}")
    temporary = path.with_name(f".{path.name}.{os.getpid()}.partial")
    owned_temporary = False
    try:
        descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        owned_temporary = True
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.link(temporary, path)
    finally:
        if owned_temporary:
            temporary.unlink(missing_ok=True)


def _source_block_metadata(weights: dict[str, tuple[Path, str, Path, dict[str, Any]]]
                            ) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for name, (path, file_sha, manifest_path, manifest) in weights.items():
        source = manifest["source"]
        index = serial_reference.BLOCK_PINS[name]["block_index"]
        result[name] = {
            "block_index": index,
            "runtime_layer_name": f"double_block_{index + 1}",
            "path": str(path),
            "file_bytes": path.stat().st_size,
            "file_sha256": file_sha,
            "manifest_path": str(manifest_path),
            "manifest_sha256": serial_reference.BLOCK_PINS[name]["manifest_sha256"],
            "source_repository": source["repository"],
            "source_revision": source["revision"],
            "source_git_commit": source["source_git_commit"],
            "checkpoint_path": source["checkpoint_path"],
            "checkpoint_lfs_sha256": source["checkpoint_lfs_sha256"],
            "source_payload_sha256": source["payload_sha256_observed"],
            "source_header_sha256": source.get("header_sha256_observed"),
            "range_start_inclusive": source["range_start_inclusive"],
            "range_end_inclusive": source["range_end_inclusive"],
            "tensor_prefix": f"double_blocks.{index}.",
            "tensor_count": 32,
        }
    return result


def produce_fixture(args: argparse.Namespace) -> dict[str, Any]:
    if os.environ.get("PYTORCH_ENABLE_MPS_FALLBACK") not in (None, "0"):
        raise ReferenceError("PYTORCH_ENABLE_MPS_FALLBACK must be unset or 0")
    os.environ["PYTORCH_ENABLE_MPS_FALLBACK"] = "0"

    output = args.output.absolute()
    if (output.suffix.lower() != ".json" or os.path.lexists(output)
            or not output.parent.is_dir()):
        raise ReferenceError("--output must be a new .json file in an existing directory")
    tensor_name = f"{output.stem}.tensors.f32le"
    tensor_path = output.parent / tensor_name
    if os.path.lexists(tensor_path):
        raise ReferenceError(f"tensor sidecar already exists: {tensor_path}")

    weights: dict[str, tuple[Path, str, Path, dict[str, Any]]] = {}
    for name, weight_arg, weight_sha_arg, manifest_arg, manifest_sha_arg in (
        ("block0", args.block0_weights, args.block0_weights_sha256,
         args.block0_manifest, args.block0_manifest_sha256),
        ("block1", args.block1_weights, args.block1_weights_sha256,
         args.block1_manifest, args.block1_manifest_sha256),
    ):
        weights[name] = serial_reference._trusted_weight_pair(
            name=name,
            weights=weight_arg,
            weights_sha256=weight_sha_arg,
            manifest_path=manifest_arg,
            manifest_sha256=manifest_sha_arg,
        )
    if weights["block0"][1] == weights["block1"][1]:
        raise ReferenceError("block1 cannot substitute block0 weights")

    upstream = args.upstream.resolve(strict=True)
    try:
        source_hashes = block_reference._verify_upstream(upstream)
    except (OSError, RuntimeError, ValueError) as exc:
        raise ReferenceError(f"pinned upstream source validation failed: {exc}") from None

    import torch
    import numpy as np

    if not torch.backends.mps.is_built() or not torch.backends.mps.is_available():
        raise ReferenceError("MPS is required; CPU fallback is forbidden")
    if torch.get_default_dtype() != torch.float32:
        torch.set_default_dtype(torch.float32)
    device = torch.device("mps")

    try:
        helpers = block_reference._install_upstream_modules(upstream)
        posemb_layers = helpers[-1]
        inputs = _generate_mps_inputs(torch, posemb_layers, device)
        original_records = {
            "input.img": inputs["img"],
            "input.txt": inputs["txt"],
            "input.vec": inputs["vec"],
            "input.vec_txt": inputs["vec_txt"],
            "input.rope_cos": inputs["rope_cos"],
            "input.rope_sin": inputs["rope_sin"],
        }

        receipt: dict[str, Any] = {"calls": 0, "query_chunks": 0, "max_query_chunk": 0}
        adapter = _build_chunked_sdpa_adapter(torch, receipt)
        records: dict[str, Any] = dict(original_records)
        model_roots: list[Any] = []
        block_inputs = inputs
        block_capture_names = [
            "img.attn.q_rope", "img.attn.k_rope", "img.output", "txt.output"
        ]
        for index, name in ((0, "block0"), (1, "block1")):
            state = serial_reference._load_block_state(torch, weights[name][0], index)
            img_output, txt_output, model, captures = _run_block(
                torch,
                upstream,
                helpers,
                posemb_layers,
                state,
                index,
                device,
                adapter,
                block_inputs,
                receipt,
            )
            records.update(captures)
            model_roots.append(model)
            block_inputs = {
                **inputs,
                "img": img_output,
                "txt": txt_output,
            }
        if receipt["calls"] != 2 or receipt["query_chunks"] != 2 * ATTENTION_CHUNKS_PER_BLOCK:
            raise ReferenceError("full-J chain did not execute the admitted two attention calls")
        raw_tensor_bytes, tensor_metadata = _serialize_tensors(torch, records)
    except ReferenceError:
        raise
    except Exception as exc:
        raise ReferenceError(
            f"full-J MPS oracle execution failed: {type(exc).__name__}: {exc}"
        ) from None

    tensor_sha = hashlib.sha256(raw_tensor_bytes).hexdigest()
    document = {
        "schema": SCHEMA,
        "schema_version": 1,
        "upstream": {
            "revision": PINNED_REVISION,
            "source_sha256": source_hashes,
        },
        "producer": {
            "path": str(Path(__file__).resolve()),
            "source_sha256": sha256_file(Path(__file__).resolve()),
            "argv": list(sys.argv),
            "python": sys.version.split()[0],
            "torch": torch.__version__,
            "numpy": np.__version__,
            "device": "mps",
            "activation_readback": "one packed final F32 tensor sidecar readback",
            "attention_adapter": "PyTorch MPS SDPA F32, query rows chunked at 256",
            "attention_adapter_calls": receipt["calls"],
            "attention_query_chunks_per_block": ATTENTION_CHUNKS_PER_BLOCK,
            "attention_query_chunk_calls": receipt["query_chunks"],
            "max_attention_query_chunk": QUERY_CHUNK,
            "block_invocations": ["block0", "block1"],
            "block_handoff": {
                "img": "block0.img.output passed directly as block1.img",
                "txt": "block0.txt.output passed directly as block1.txt",
                "same_mps_tensor_objects": True,
            },
            "captures_per_block": block_capture_names,
            "terminal_tensor_count": len(records),
            "terminal_sidecar_bytes": len(raw_tensor_bytes),
        },
        "source": {
            "blocks": _source_block_metadata(weights),
        },
        "geometry": dict(GEOMETRY),
        "input_generation": json.loads(json.dumps(INPUT_GENERATION)),
        "precision": dict(PRECISION),
        "tolerance": {"atol": ATOL, "rtol": RTOL},
        "limitations": [
            "img, txt, vec, and vec_txt are deterministic synthetic MPS inputs, not a saved conditioning or full-generation path",
            "PyTorch MPS F32 SDPA with query chunks of 256 substitutes for Magi/Flash attention; it does not establish their numerical parity",
            "weights use F32 parameter storage containing BF16-rounded values; this does not test physical BF16-resident parameter storage or native BF16 compute",
            "the admitted chain covers actual block 0 followed by actual block 1 only, not the remaining DiT blocks or media generation",
        ],
        "tensor_file": {
            "name": tensor_name,
            "nbytes": len(raw_tensor_bytes),
            "sha256": tensor_sha,
            "encoding": "f32-le",
        },
        "tensors": tensor_metadata,
    }
    validate_reference_document(document)
    validate_tensor_layout(tensor_metadata, len(raw_tensor_bytes))
    json_bytes = (json.dumps(document, indent=2, sort_keys=True) + "\n").encode("utf-8")
    if len(json_bytes) > JSON_LIMIT:
        raise ReferenceError("reference JSON exceeds the 2 MiB bound")
    _publish_noreplace(tensor_path, raw_tensor_bytes)
    try:
        _publish_noreplace(output, json_bytes)
    except Exception:
        tensor_path.unlink(missing_ok=True)
        raise
    return {
        "status": "created",
        "output": str(output),
        "tensor_file": str(tensor_path),
        "tensor_file_sha256": tensor_sha,
        "tensor_count": len(tensor_metadata),
        "tensor_bytes": len(raw_tensor_bytes),
        "attention_adapter_calls": receipt["calls"],
        "attention_query_chunk_calls": receipt["query_chunks"],
        "upstream_revision": PINNED_REVISION,
    }


def main(argv: list[str] | None = None) -> int:
    args = _build_cli().parse_args(argv)
    try:
        result = produce_fixture(args)
    except (OSError, ValueError, ReferenceError, ImportError, RuntimeError) as exc:
        raise SystemExit(str(exc)) from exc
    print(json.dumps(result, sort_keys=True))
    return 0


